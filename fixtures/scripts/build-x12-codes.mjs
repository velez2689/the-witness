// Build src/domain/x12-codes.ts from the two X12 code lists: identifiers only.
//
//   node fixtures/scripts/build-x12-codes.mjs [rarcSource] [claimStatusSource]
//
// Each source is a URL (fetched) or a local file: the page's HTML, its Markdown, or a JSON object
// with a `markdown` field (what a scraper hands back). Defaults to the two x12.org pages:
//   https://x12.org/codes/remittance-advice-remark-codes
//   https://x12.org/codes/claim-status-codes
//
// What ships: the code identifier, whether it is still active (no Stop date), and a coarse bucket
// WE assign by keyword over the description. The description itself is X12's copyrighted text and
// is never written out; the output is checked so that no field is longer than eight characters.
import { readFileSync, writeFileSync } from 'node:fs';

const SOURCES = [
  process.argv[2] ?? 'https://x12.org/codes/remittance-advice-remark-codes',
  process.argv[3] ?? 'https://x12.org/codes/claim-status-codes',
];
const OUT = 'src/domain/x12-codes.ts';

async function load(src) {
  const raw = /^https?:/.test(src) ? await (await fetch(src)).text() : readFileSync(src, 'utf8');
  if (raw.trimStart().startsWith('{')) {
    const j = JSON.parse(raw);
    if (typeof j.markdown === 'string') return j.markdown;
  }
  return raw;
}

/** Table rows "| CODE | text |" from Markdown, or "<td>CODE</td><td>text</td>" from HTML. */
function rows(text, codeRe) {
  const out = [];
  const md = /^\|\s*([A-Z0-9]{1,6})\s*\|\s*(.*?)\s*\|\s*$/gm;
  for (const m of text.matchAll(md)) if (codeRe.test(m[1])) out.push({ code: m[1], desc: m[2] });
  if (out.length > 0) return out;
  const html = /<td[^>]*>\s*([A-Z0-9]{1,6})\s*<\/td>\s*<td[^>]*>([\s\S]*?)<\/td>/g;
  for (const m of text.matchAll(html)) if (codeRe.test(m[1])) out.push({ code: m[1], desc: m[2].replace(/<[^>]+>/g, ' ') });
  return out;
}

/** Our own coarse label. Derived from the description at build time; the description is not kept. */
function bucket(desc) {
  const d = desc.toLowerCase();
  if (/^alert:/.test(d)) return 'alert';
  if (/duplicate/.test(d)) return 'duplicate';
  if (/timely|time limit|filing limit|filed late|late filing/.test(d)) return 'timely_filing';
  if (/authoriz|pre-?cert|referral/.test(d)) return 'authorization';
  if (/primary payer|other insurance|other payer|coordination|secondary|medicare secondary|liability/.test(d)) return 'coordination_of_benefits';
  if (/eligib|enroll|entitle|coverage (was|has been|is) terminated|not a member/.test(d)) return 'eligibility';
  if (/not covered|non-?covered|not a covered|excluded|benefit|coverage/.test(d)) return 'coverage';
  if (/procedure code|diagnosis|modifier|cpt|hcpcs|ndc|revenue code|place of service|units|bundl|\bcode\b/.test(d)) return 'coding';
  if (/documentation|records|attachment|missing|incomplete|invalid|information|signature|form/.test(d)) return 'documentation';
  if (/payment|paid|allowed|fee schedule|reimburs|adjust|deductible|coinsurance|copay/.test(d)) return 'payment';
  return 'other';
}

const [rarcText, statusText] = await Promise.all(SOURCES.map(load));
const rarc = rows(rarcText, /^(M\d{1,3}|MA\d{1,3}|N\d{1,3})$/);
const status = rows(statusText, /^\d{1,3}$/);
if (rarc.length < 500 || status.length < 300) {
  throw new Error(`too few codes parsed: RARC ${rarc.length}, claim status ${status.length}`);
}

const entry = ({ code, desc }) => {
  const active = !/\bStop:/i.test(desc);
  const b = bucket(desc);
  for (const field of [code, active ? 'y' : 'n', b]) {
    if (field.length > 24) throw new Error(`field too long for ${code}: ${field}`);
  }
  return `  ${/^\d/.test(code) ? `'${code}'` : code}: [${active ? 1 : 0}, '${b}'],`;
};
const dedupe = (list) => [...new Map(list.map((r) => [r.code, r])).values()];

const body = `// GENERATED by fixtures/scripts/build-x12-codes.mjs on ${new Date().toISOString().slice(0, 10)}. Do not edit.
//
// Identifiers from the X12 Remittance Advice Remark Code and Claim Status Code lists (x12.org).
// Only the code, whether it is still active, and a coarse bucket we assign are stored. The
// descriptions are X12's copyrighted text and never ship in this repository; codes render as
// opaque strings, the same rule as CPT.

export type CodeBucket =
  | 'alert'
  | 'authorization'
  | 'coding'
  | 'coordination_of_benefits'
  | 'coverage'
  | 'documentation'
  | 'duplicate'
  | 'eligibility'
  | 'other'
  | 'payment'
  | 'timely_filing';

/** [active, bucket]: 1 when the code has no Stop date on the list. */
export type CodeEntry = readonly [0 | 1, CodeBucket];

/** Remittance Advice Remark Codes (RARC): M, MA and N series. */
export const RARC: Readonly<Record<string, CodeEntry>> = {
${dedupe(rarc).map(entry).join('\n')}
};

/** Claim Status Codes (X12 277). */
export const CLAIM_STATUS: Readonly<Record<string, CodeEntry>> = {
${dedupe(status).map(entry).join('\n')}
};

/** "n 30", "N-30", "ma130" -> "N30" / "MA130", or null when not a remark-code shape. */
export function normalizeRemarkCode(raw: string): string | null {
  const m = /^(MA|M|N)[\\s-]?(\\d{1,3})$/i.exec(raw.trim());
  return m ? \`\${m[1].toUpperCase()}\${String(Number(m[2]))}\` : null;
}

export function remarkCode(code: string): { known: boolean; active: boolean; bucket: CodeBucket | null } {
  const e = RARC[code];
  return e ? { known: true, active: e[0] === 1, bucket: e[1] } : { known: false, active: false, bucket: null };
}

export function claimStatusCode(code: string): { known: boolean; active: boolean; bucket: CodeBucket | null } {
  const e = CLAIM_STATUS[String(Number(code))];
  return e ? { known: true, active: e[0] === 1, bucket: e[1] } : { known: false, active: false, bucket: null };
}
`;
writeFileSync(OUT, body);
console.log(`wrote ${OUT}: ${dedupe(rarc).length} remark codes, ${dedupe(status).length} claim status codes`);
